function showSection(index) {
    currentSectionIndex = index;
    const section = rulesSections[index];
    displayTitle.textContent = section.title;
    displayContent.innerHTML = section.content;
    document.querySelectorAll('.toc-list button').forEach((btn, i) => {
        if (i == index) btn.classList.add('active-section');
        else btn.classList.remove('active-section');
    });
    clearHighlight();
}

function clearHighlight() {
    const html = displayContent.innerHTML;
    const cleanHtml = html.replace(/<span class="highlight">(.*?)<\/span>/gi, '$1');
    displayContent.innerHTML = cleanHtml;
}

