const clearBtn = document.getElementById('clearSearchBtn');

function searchAndDisplay() {
    const term = searchInput.value.trim();
    if (!term) { clearHighlight(); return; }
    const regex = new RegExp(`(${term.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')})`, 'gi');
    let foundIndex = -1;
    let foundContent = null;
    for (let i = 0; i < rulesSections.length; i++) {
        const content = rulesSections[i].content;
        if (regex.test(content)) {
            foundIndex = i;
            foundContent = content;
            break;
        }
    }
    if (foundIndex !== -1) {
        showSection(foundIndex);
        const highlighted = foundContent.replace(regex, `<span class="highlight">$1</span>`);
        displayContent.innerHTML = highlighted;
        const firstHighlight = displayContent.querySelector('.highlight');
        if (firstHighlight) firstHighlight.scrollIntoView({ behavior: 'smooth', block: 'center' });
    } else {
        showToast('Ничего не найдено');
        clearHighlight();
    }
}

